from typing import Optional

import dspy

from ...base_dspy import BaseDspy


class VerifyBugDetect(dspy.Signature):
	detected_bugs: str = dspy.InputField(
		desc="The bug description(s) generated by the bug detection model. May contain multiple bugs."
	)

	buggy_code: str = dspy.InputField(
		desc="The original buggy code snippet related to the detected bugs."
	)

	ground_truth_bug: str = dspy.InputField(
		desc="The single ground truth bug description (reference standard)"
	)

	is_correct: bool = dspy.OutputField(
		desc=(
			"Determine if the detected bugs contain the ground truth bug:\n"
			"1. Semantic matching:\n"
			"   - Check if ANY of the detected bugs semantically matches the ground truth\n"
			"   - The core issue in ground truth must be identified, even if wording differs\n"
			"   - Example: 'null pointer exception' matches 'dereferencing null object'\n"
			"2. Partial detection is OK:\n"
			"   - Return True if the ground truth bug is found, even if:\n"
			"     * Additional bugs are also reported (false positives are acceptable)\n"
			"     * The description has extra details\n"
			"     * The wording is different but meaning is the same\n"
			"3. Return False only if:\n"
			"   - The ground truth bug is completely missed\n"
			"   - The detected bugs describe a different issue entirely\n"
			"   - The description is too vague to confirm the ground truth bug\n"
			"Focus on whether the ground truth bug is detected, not on precision."
		)
	)

	confidence: float = dspy.OutputField(
		desc=(
			"Provide a confidence score from 0.0 to 1.0 indicating match quality:\n"
			"- 1.0: Perfect match - ground truth bug clearly and accurately described\n"
			"- 0.8-0.9: Strong match - ground truth bug identified with minor wording differences\n"
			"- 0.6-0.7: Good match - ground truth bug detected but description lacks some details\n"
			"- 0.4-0.5: Weak match - ground truth bug vaguely mentioned or partially described\n"
			"- 0.2-0.3: Poor match - unclear if ground truth bug was actually detected\n"
			"- 0.0-0.1: No match - ground truth bug completely missed\n"
			"Note: Confidence should be high even if extra bugs are reported (false positives don't lower confidence)."
		)
	)

	explanation: str = dspy.OutputField(
		desc=(
			"Provide a brief explanation (2-3 sentences) for the verification result:\n"
			"- If True: explain how the ground truth bug was detected and quote relevant parts\n"
			"- If False: explain why the ground truth bug was not found\n"
			"- Mention the confidence score reasoning\n"
			"Be specific and reference both detected and ground truth descriptions."
		)
	)


class BugDetectionVerifier(BaseDspy):
	def _post_init(self, **kwargs):
		self.verify_signature = VerifyBugDetect

	def verify(
		self, detected_bugs: str, buggy_code: str, ground_truth_bug: str, max_tries: int = 3
	) -> Optional[dict]:
		with self.use_model():
			verifier = dspy.ChainOfThought(self.verify_signature)

			for attempt in range(max_tries):
				try:
					result = verifier(
						detected_bugs=detected_bugs,
						buggy_code=buggy_code,
						ground_truth_bug=ground_truth_bug,
					)
					return {
						"is_correct": result.is_correct,
						"confidence": result.confidence,
						"explanation": result.explanation,
					}
				except Exception as e:
					print(f"Verification attempt {attempt + 1}/{max_tries} failed: {e}")
					if attempt == max_tries - 1:
						raise RuntimeError(f"Bug verification failed after {max_tries} attempts") from e

			print(f"All {max_tries} verification attempts failed.")
			return None
